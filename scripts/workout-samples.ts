/**
 * Writes docs/WORKOUT_SAMPLES.md: complete 4-week sample programs produced by
 * the generator, so the documented plans always match what the app shows.
 *
 *   npx tsx scripts/workout-samples.ts
 */
import { writeFileSync } from "node:fs";
import { getExercise } from "../src/lib/workouts/exercises";
import { generateProgram, type ProgramInput } from "../src/lib/workouts/generator";
import { estimateDay } from "../src/lib/workouts/load";
import type { Prescription } from "../src/lib/workouts/types";

const SAMPLES: { title: string; who: string; input: ProgramInput }[] = [
  {
    title: "Home · Beginner · Weight loss · 3 days/week (no equipment)",
    who: "Woman, 72 kg, no equipment",
    input: { location: "home", level: "beginner", goal: "lose", daysPerWeek: 3, equipment: [], sex: "female", weightKg: 72 },
  },
  {
    title: "Gym · Beginner · Stay fit · 3 days/week (full body)",
    who: "Man, 68 kg",
    input: { location: "gym", level: "beginner", goal: "fit", daysPerWeek: 3, equipment: [], sex: "male", weightKg: 68 },
  },
  {
    title: "Gym · Intermediate · Muscle gain · 4 days/week (upper / lower)",
    who: "Man, 75 kg",
    input: { location: "gym", level: "intermediate", goal: "gain", daysPerWeek: 4, equipment: [], sex: "male", weightKg: 75 },
  },
  {
    title: "Gym · Advanced · Muscle gain · 6 days/week (push / pull / legs)",
    who: "Woman, 60 kg",
    input: { location: "gym", level: "advanced", goal: "gain", daysPerWeek: 6, equipment: [], sex: "female", weightKg: 60 },
  },
];

function dose(p: Prescription) {
  const ex = getExercise(p.exerciseId);
  const side = ex.perSide ? "/side" : "";
  const secs = p.seconds ?? 0;
  const time = secs >= 120 ? `${Math.round(secs / 60)} min` : `${secs}s`;
  const amount = p.reps ? (p.reps[0] === p.reps[1] ? `${p.reps[0]}` : `${p.reps[0]}–${p.reps[1]}`) + side : `${time}${side}`;
  const each = ex.load?.implement === "dumbbell" && !ex.load.single;
  const load = p.loadKg != null ? ` @ ${p.loadKg} kg${each ? " each" : ""}` : "";
  return p.sets === 1 && !p.reps ? `${amount}` : `${p.sets} × ${amount}${load}`;
}

const out: string[] = [
  "# Sample workout programs",
  "",
  "Generated by `scripts/workout-samples.ts` from `src/lib/workouts/generator.ts` — re-run it after changing the",
  "generator or the exercise library. Loads are conservative first-session suggestions; after each session the app",
  "adjusts them from what was actually lifted (double progression). Times and kcal are estimates (MET method).",
  "",
  "> Check with a doctor before starting a new exercise programme, especially if you are pregnant, have a heart,",
  "> blood-pressure, joint or other medical condition, or have been inactive for a long time.",
  "",
];

for (const s of SAMPLES) {
  const p = generateProgram(s.input);
  out.push(`## ${s.title}`, "", `*${p.name}* — sample person: ${s.who}.`, "");
  for (let w = 1; w <= p.weeks; w++) {
    out.push(`### Week ${w}`, "", "| Day | Session | Exercises (sets × reps, rest) | ≈ min | ≈ kcal |", "|---|---|---|---|---|");
    for (const d of p.days.filter((d) => d.week === w)) {
      const e = estimateDay(d, s.input.weightKg);
      const label = d.kind === "rest" ? "Rest" : d.kind === "recovery" ? "Active recovery" : `${d.focus.replace("_", " + ")} (${d.setting})${d.isIntro ? " — intro" : ""}`;
      const items =
        d.kind === "rest"
          ? "Rest, walk normally, sleep well"
          : d.main.map((m) => `${getExercise(m.exerciseId).name} ${dose(m)}${d.kind === "workout" ? `, ${m.restSec}s` : ""}`).join("<br>");
      out.push(`| ${d.index + 1} | ${label} | ${items} | ${e.minutes || "—"} | ${e.kcal || "—"} |`);
    }
    out.push("");
  }
  const first = p.days[0];
  out.push(
    "Every workout starts with a warm-up — " + first.warmup.map((m) => getExercise(m.exerciseId).name.toLowerCase()).join(", "),
    "— and ends with a cool-down — " + first.cooldown.map((m) => getExercise(m.exerciseId).name.toLowerCase()).join(", ") + ".",
    "",
  );
}

writeFileSync(new URL("../docs/WORKOUT_SAMPLES.md", import.meta.url), out.join("\n"));
console.log("✓ wrote docs/WORKOUT_SAMPLES.md");
